'use strict';

// Whisper обучался в том числе на субтитрах с видеохостингов, поэтому на тишине
// и шуме уверенно «дописывает» титры и концовки роликов: «Субтитры сделал
// DimaTorzok», «Подписывайтесь на канал», «Subtitles by the Amara.community».
// В расшифровке созвона это мусор, который ещё и уезжает в факты и итоги.
//
// Правило отбора шаблонов: вырезаем только то, что в рабочем разговоре
// осмысленно прозвучать не может. Например, «Спасибо за внимание» — обычная
// фраза на созвоне, её не трогаем, а «Спасибо за просмотр» — титры.

// Хвост фразы: добираем до конца предложения, но точку внутри слова глотаем —
// иначе матч рвётся на инициалах («А.Синецкая») и доменах («Amara.community»).
// Концом считаем только знак, за которым идёт пробел или конец строки.
const TAIL = '(?:[^.!?\\n]|[.!?](?!\\s|$))*';
const phrase = (body) => new RegExp(body + TAIL, 'giu');

const PATTERNS = [
  // Титры субтитровщиков во всех известных вариантах
  phrase('субтитр\\p{L}*\\s+(?:сделал\\p{L}*|создавал\\p{L}*|делал\\p{L}*|подготов\\p{L}+|предоставл\\p{L}+|редактировал\\p{L}*|перев[ёе]л|перевод)'),
  phrase('(?:редактор|корректор|автор)\\s+субтитров'),
  // «Спасибо за субтитры Алексею Дубровскому!» и родня
  phrase('спасибо\\s+(?:вам\\s+)?за\\s+субтитр\\p{L}*'),
  phrase('субтитры\\s+и\\s+перевод'),
  new RegExp('dima\\s*_?\\s*torzok', 'giu'),

  // Концовки роликов
  phrase('подписывайтесь\\s+на\\s+(?:наш\\s+|мой\\s+)?канал'),
  phrase('(?:ставьте\\s+лайк\\p{L}*|поставь(?:те)?\\s+лайк)'),
  phrase('не\\s+забуд(?:ьте|ь)\\s+(?:подписаться|поставить\\s+лайк)'),
  phrase('спасибо\\s+за\\s+просмотр'),
  phrase('продолжение\\s+следует'),

  // Английские аналоги
  phrase('subtitles?\\s+(?:by|created\\s+by|provided\\s+by)'),
  new RegExp('amara\\.(?:org|community)', 'giu'),
  phrase('thanks?\\s+(?:you\\s+)?for\\s+watching'),
  phrase('please\\s+subscribe'),
  phrase('like\\s+and\\s+subscribe')
];

/** Осталась ли в строке хоть одна буква или цифра. */
const hasContent = (text) => /[\p{L}\p{N}]/u.test(text);

/**
 * Вырезает известные галлюцинации whisper.
 * Если после вырезания осмысленного текста не осталось — возвращает пустую строку,
 * и сегмент дальше не пойдёт вовсе.
 */
function stripHallucinations(text, extraPatterns = []) {
  let out = String(text || '');
  for (const re of [...PATTERNS, ...extraPatterns]) {
    out = out.replace(re, ' ');
  }
  // Подчищаем то, что осталось от вырезанного: висящие знаки и двойные пробелы.
  out = out
    .replace(/\s+([,.!?;:])/g, '$1')
    .replace(/([,.!?;:])\s*(?=[,.!?;:])/g, '')
    .replace(/\s+/g, ' ')
    .replace(/^[\s.,!?;:—–-]+/, '')
    .replace(/[\s,;:—–-]+$/, '')
    .trim();

  return hasContent(out) ? out : '';
}

/** Пользовательские фразы из настроек: по одной на строку. */
function compileExtra(list) {
  const lines = String(list || '')
    .split(/\r?\n/)
    .map((s) => s.trim())
    .filter(Boolean);
  return lines.map((line) => new RegExp(line.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi'));
}

module.exports = { stripHallucinations, compileExtra, PATTERNS };
